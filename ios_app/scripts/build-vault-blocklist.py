#!/usr/bin/env python3
"""Build the vault browser's ad + tracker block list from EasyList and EasyPrivacy.

Writes JarvisCopilot/Copilot/Vault/VaultBlocklist.generated.swift: the blocked hosts and the
generic element-hiding selectors, as two string literals the app turns into a WebKit content rule
list on first use (compiled once, then cached by version). The list ships inside the app, so the
browser never asks anyone what to block.

Source lists: https://easylist.to — EasyList and EasyPrivacy, used under CC BY-SA 3.0
(they are dual-licensed GPLv3 / CC BY-SA 3.0). Re-run to refresh:
    python3 scripts/build-vault-blocklist.py
"""
from __future__ import annotations

import datetime
import hashlib
import re
import sys
import urllib.request
from pathlib import Path

SOURCES = {
    "EasyList": "https://easylist.to/easylist/easylist.txt",
    "EasyPrivacy": "https://easylist.to/easylist/easyprivacy.txt",
}
OUT = Path(__file__).resolve().parents[1] / "JarvisCopilot/Copilot/Vault/VaultBlocklist.generated.swift"
MAX_HOSTS = 150_000 - 1_000   # WebKit's per-list cap, minus room for the selector rules
MAX_SELECTORS = 6_000

HOST_RULE = re.compile(r"^\|\|([a-z0-9][a-z0-9.-]*\.[a-z]{2,})\^(\$third-party)?$")
SAFE_SELECTOR = re.compile(r"^[A-Za-z0-9_\-#.\[\]=\"'^$*~|: >+,()]+$")


def fetch(url: str) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "jarvis-blocklist-builder"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read().decode("utf-8", errors="replace")


def main() -> int:
    hosts: dict[str, bool] = {}          # host -> third-party only
    selectors: list[str] = []
    seen_sel: set[str] = set()
    for name, url in SOURCES.items():
        text = fetch(url)
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith(("!", "[", "@@")):
                continue
            m = HOST_RULE.match(line)
            if m:
                host, third = m.group(1), bool(m.group(2))
                hosts[host] = hosts.get(host, True) and third
                continue
            if line.startswith("##") and len(selectors) < MAX_SELECTORS:
                sel = line[2:]
                # Plain CSS only: no procedural (:has, :-abp-) or extended selectors WebKit rejects.
                if (":" in sel and not re.search(r":(not|nth-child|nth-of-type|first-child|last-child)\(", sel)
                        and ":" in re.sub(r":(not|nth-child|nth-of-type|first-child|last-child)\([^)]*\)", "", sel)):
                    continue
                if not SAFE_SELECTOR.match(sel) or sel in seen_sel:
                    continue
                seen_sel.add(sel)
                selectors.append(sel)
    # A host already covered by its parent domain is redundant.
    names = set(hosts)
    kept = sorted(h for h in names if not any(".".join(h.split(".")[i:]) in names for i in range(1, h.count("."))))
    print(f"{len(names)} host rules, {len(kept)} after dropping covered subdomains", file=sys.stderr)
    kept = kept[:MAX_HOSTS]
    lines = [("3 " if hosts[h] else "") + h for h in kept]      # "3 " marks third-party-only rules
    body = "\n".join(lines)
    sel_body = "\n".join(selectors)
    version = hashlib.sha256((body + "\0" + sel_body).encode()).hexdigest()[:12]
    today = datetime.date.today().isoformat()
    for s in (body, sel_body):
        if '"""#' in s:
            raise SystemExit("a list entry would end the raw string literal")
    OUT.write_text(f'''// GENERATED by scripts/build-vault-blocklist.py on {today}. Do not edit by hand.
// Hosts and generic element-hiding selectors from EasyList and EasyPrivacy (https://easylist.to),
// used under CC BY-SA 3.0. {len(kept)} hosts, {len(selectors)} selectors.

enum VaultBlocklist {{
    static let version = "{version}"

    /// One host per line; a leading "3 " means "only when loaded by another site".
    static let hosts = #"""
{body}
"""#

    /// One CSS selector per line, hidden on every page.
    static let selectors = #"""
{sel_body}
"""#
}}
''')
    print(f"{len(kept)} hosts, {len(selectors)} selectors, version {version} -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
