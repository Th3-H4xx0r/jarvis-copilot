static Bytes from_hex(const char* hex) {
  Bytes out;
  const size_t n = std::strlen(hex);
  for (size_t i = 0; i + 1 < n; i += 2) {
    auto nib = [](char c) -> uint8_t { return c <= '9' ? c - '0' : (c | 0x20) - 'a' + 10; };
    out.push_back(static_cast<uint8_t>((nib(hex[i]) << 4) | nib(hex[i + 1])));
  }
  return out;
}

static std::string to_hex(const Bytes& b) {
  static const char* d = "0123456789abcdef";
  std::string s;
  for (uint8_t c : b) { s += d[c >> 4]; s += d[c & 15]; }
  return s;
}

// Same sequence the generator's fake os.urandom hands out: 16 bytes → the client nonce,
// the k-th 12-byte request → (k*16 + i).
static int g_iv_counter = 0;
static void fixed_rng(uint8_t* out, size_t n) {
  if (n == 16) {
    const Bytes nonce = from_hex(kClientNonce);
    std::memcpy(out, nonce.data(), 16);
  } else {
    for (size_t i = 0; i < n; ++i) out[i] = static_cast<uint8_t>(g_iv_counter * 16 + static_cast<int>(i));
    ++g_iv_counter;
  }
}

static Bytes take(Session& s) {
  Bytes out;
  s.take_output(out);
  return out;
}

static void feed(Session& s, const Bytes& b, uint32_t now) { s.feed(b.data(), b.size(), now, kT); }
static void feed_hex(Session& s, const char* hex, uint32_t now) { feed(s, from_hex(hex), now); }

static std::vector<Session::Report> reports(Session& s) {
  std::vector<Session::Report> out;
  Session::Report r;
  while (s.take_report(r)) out.push_back(r);
  return out;
}

static Bytes key() { return from_hex(kLocalKey); }

