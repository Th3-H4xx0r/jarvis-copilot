static void test_v33_session() {
  g_iv_counter = 0;
  const Bytes k = key();
  Session s(fixed_rng);
  s.start(Version::v33, kDevId, k.data(), 1000, kT);
  CHECK(s.phase() == Session::Phase::awaiting_first);
  CHECK_HEX(take(s), k33Query);
  CHECK(!s.ready());

  // Query reply, fed one byte at a time to exercise reassembly.
  const Bytes reply = from_hex(k33QueryReply);
  for (uint8_t b : reply) s.feed(&b, 1, 1100, kT);
  CHECK(s.ready());
  CHECK(s.phase() == Session::Phase::ready);
  auto r = reports(s);
  CHECK(r.size() == 1);
  if (r.size() == 1) {
    CHECK(r[0].cmd == cmd::dp_query);
    CHECK(r[0].json == k33QueryReplyJson);
    CHECK(r[0].query);  // answers the connect-time DP_QUERY
  }

  // Line noise ahead of a status push: resync on the prefix.
  Bytes noisy = {0x01, 0x02, 0x00, 0x00, 0x55};
  const Bytes status = from_hex(k33Status);
  noisy.insert(noisy.end(), status.begin(), status.end());
  feed(s, noisy, 1200);
  r = reports(s);
  CHECK(r.size() == 1);
  if (r.size() == 1) {
    CHECK(r[0].cmd == cmd::status);
    CHECK(r[0].json == k33StatusJson);
    CHECK(!r[0].query);  // an unsolicited push
  }

  // Two frames in one read.
  Bytes two = status;
  two.insert(two.end(), status.begin(), status.end());
  feed(s, two, 1300);
  CHECK(reports(s).size() == 2);

  // CRC mismatch: dropped, session survives.
  Bytes bad = status;
  bad[30] ^= 0x01;
  feed(s, bad, 1400);
  CHECK(reports(s).empty());
  CHECK(s.ready());
  CHECK(s.dropped_frames() == 1);

  // Heartbeat after 10 s (seq 2), then the control (seq 3): byte-exact with tinytuya.
  s.tick(11000, kT);
  CHECK_HEX(take(s), k33Heartbeat);
  CHECK(s.rtt_ms() == -1);
  feed_hex(s, k33HeartbeatAck, 11042);
  CHECK(s.rtt_ms() == 42);
  CHECK(s.control("{\"1\":true,\"101\":\"arm\"}", kT));
  CHECK_HEX(take(s), k33Control);

  // No traffic for 30 s: the link is dead.
  s.tick(41041, kT);
  CHECK(s.ready());
  take(s);  // heartbeats
  s.tick(41043, kT);
  CHECK(s.phase() == Session::Phase::failed);
  CHECK(s.failure() == Session::Failure::went_silent);
}

