import AppKit
import XCTest
@testable import Jarvis

/// Flow dictation's pure rules: the hold / double-tap key, which physical key is
/// down, the dictionary, replacements, snippets and per-app styles, the paste
/// and its clipboard restore, the history and the numbers.
final class FlowTests: XCTestCase {

    // MARK: the key

    func testHoldDictatesAndReleasePastes() {
        var k = FlowKeyLogic()
        XCTAssertEqual(k.keyDown(at: 0), .start)
        XCTAssertEqual(k.keyDown(at: 0.1), .none, "key repeat")
        XCTAssertEqual(k.keyUp(at: 1.0), .finish)
        XCTAssertEqual(k.phase, .idle)
    }

    func testDoubleTapIsHandsFreeUntilTheNextTap() {
        var k = FlowKeyLogic()
        XCTAssertEqual(k.keyDown(at: 0), .start)
        XCTAssertEqual(k.keyUp(at: 0.1), .none)
        XCTAssertEqual(k.phase, .tapWait(until: 0.1 + FlowKeyLogic.doubleTapWindow))
        XCTAssertEqual(k.keyDown(at: 0.3), .lock)
        XCTAssertEqual(k.keyUp(at: 0.35), .none, "the second tap's release keeps it going")
        XCTAssertEqual(k.phase, .locked)
        XCTAssertEqual(k.keyDown(at: 9), .finish)
        XCTAssertEqual(k.phase, .idle)
    }

    func testALoneShortTapIsDroppedWhenTheWindowRunsOut() {
        var k = FlowKeyLogic()
        _ = k.keyDown(at: 0)
        _ = k.keyUp(at: 0.1)
        XCTAssertEqual(k.tick(at: 0.2), .none, "still inside the window")
        XCTAssertEqual(k.tick(at: 0.6), .cancel)
        XCTAssertEqual(k.phase, .idle)
    }

    func testASecondPressAfterAMissedTimeoutStartsAfresh() {
        var k = FlowKeyLogic()
        _ = k.keyDown(at: 0)
        _ = k.keyUp(at: 0.1)
        XCTAssertEqual(k.keyDown(at: 2), .restart)
        XCTAssertEqual(k.keyUp(at: 3), .finish)
    }

    func testAnotherKeyMeansItWasAShortcut() {
        var k = FlowKeyLogic()
        _ = k.keyDown(at: 0)
        XCTAssertEqual(k.otherKey(), .cancel)
        XCTAssertEqual(k.phase, .idle)
        var locked = FlowKeyLogic()
        locked.lock()
        XCTAssertEqual(locked.otherKey(), .none, "typing while hands-free is fine")
    }

    func testEscapeCancelsAnything() {
        var k = FlowKeyLogic()
        XCTAssertEqual(k.escape(), .none)
        k.lock()
        XCTAssertEqual(k.escape(), .cancel)
        XCTAssertEqual(k.phase, .idle)
    }

    func testTheRightKeyIsToldFromTheLeftOne() {
        let rightOption = NSEvent.ModifierFlags(rawValue: NSEvent.ModifierFlags.option.rawValue | 0x40)
        let leftOption = NSEvent.ModifierFlags(rawValue: NSEvent.ModifierFlags.option.rawValue | 0x20)
        XCTAssertTrue(FlowKey.rightOption.isDown(rightOption))
        XCTAssertFalse(FlowKey.rightOption.isDown(leftOption))
        XCTAssertTrue(FlowKey.rightCommand.isDown(NSEvent.ModifierFlags(rawValue: NSEvent.ModifierFlags.command.rawValue | 0x10)))
        XCTAssertTrue(FlowKey.fn.isDown(.function))
        XCTAssertEqual(FlowKey(rawValue: "nonsense"), nil)
        XCTAssertEqual(FlowKey.stored(nil), .rightOption, "right ⌥ by default")
    }

    func testPasteAgainIsControlCommandV() {
        XCTAssertTrue(FlowPaste.isPasteAgain(characters: "v", flags: [.command, .control]))
        XCTAssertTrue(FlowPaste.isPasteAgain(characters: "V", flags: [.command, .control, .capsLock]))
        XCTAssertFalse(FlowPaste.isPasteAgain(characters: "v", flags: [.command]))
        XCTAssertFalse(FlowPaste.isPasteAgain(characters: "v", flags: [.command, .control, .shift]))
    }

    // MARK: the clipboard

    func testTheClipboardIsRestoredOnlyIfNothingElseWasCopied() {
        XCTAssertTrue(FlowPaste.shouldRestore(changeCountAfterPaste: 7, changeCountNow: 7))
        XCTAssertFalse(FlowPaste.shouldRestore(changeCountAfterPaste: 7, changeCountNow: 8),
                       "the user copied something meanwhile: theirs wins")
    }

    func testTheWordsAreMarkedTransient() {
        XCTAssertEqual(FlowPaste.transientType.rawValue, "org.nspasteboard.TransientType")
        XCTAssertEqual(FlowPaste.autoGeneratedType.rawValue, "org.nspasteboard.AutoGeneratedType")
    }

    // MARK: words

    func testReplacementsMatchWholeWordsAnyCaseAnySeparator() {
        let r = [FlowReplacement(from: "cloud code", to: "Claude Code")]
        XCTAssertEqual(FlowText.apply("open Cloud-Code now", words: [], replacements: r, snippets: []),
                       "open Claude Code now")
        let art = [FlowReplacement(from: "art", to: "ART")]
        XCTAssertEqual(FlowText.apply("depart art", words: [], replacements: art, snippets: []), "depart ART")
    }

    func testTheDictionaryFixesSpelling() {
        XCTAssertEqual(FlowText.apply("deploy to supabase", words: ["Supabase"], replacements: [], snippets: []),
                       "deploy to Supabase")
        XCTAssertEqual(FlowText.apply("learn c today", words: ["C++"], replacements: [], snippets: []),
                       "learn c today", "a word with symbols would match every lone letter")
    }

    func testSnippetsAreSetAsideThenPutBack() {
        let s = [FlowSnippet(trigger: "my signature", text: "Best,\nPranav")]
        let prepared = FlowText.prepare("thanks my signature", words: [], replacements: [FlowReplacement(from: "best", to: "WORST")],
                                        snippets: s)
        XCTAssertEqual(prepared.text, "thanks ⟦1⟧")
        XCTAssertEqual(FlowText.finish(prepared.text, snippets: prepared.snippets), "thanks Best,\nPranav",
                       "replacements never touch a snippet's own text")
        XCTAssertTrue(FlowText.keepsMarks("Thanks, ⟦1⟧", prepared.snippets))
        XCTAssertFalse(FlowText.keepsMarks("Thanks.", prepared.snippets))
    }

    func testWordCount() {
        XCTAssertEqual(FlowText.wordCount("it's a test ?"), 3)
        XCTAssertEqual(FlowText.wordCount(""), 0)
    }

    func testPerAppStyles() {
        let styles = [FlowAppStyle(bundleID: "com.apple.mail", name: "Mail", style: .polished)]
        XCTAssertEqual(FlowStyle.resolve(bundleID: "com.apple.mail", in: styles, default: .natural), .polished)
        XCTAssertEqual(FlowStyle.resolve(bundleID: "com.other", in: styles, default: .natural), .natural)
        XCTAssertEqual(FlowStyle.resolve(bundleID: nil, in: styles, default: .verbatim), .verbatim)
        XCTAssertTrue(FlowAppStyle.defaults.contains { $0.bundleID == "com.apple.Terminal" && $0.style == .natural })
    }

    /// Code and AI apps get Jarvis's light clean-up too ("natural"), not the
    /// words as heard: a prompt to Claude reads better without the "uh"s. (They
    /// were "as said", so dictating in VS Code never reached Jarvis.)
    func testCodeAndAIAppsAreCleanedByDefault() {
        for id in FlowAppStyle.codeApps {
            XCTAssertEqual(FlowAppStyle.defaults.first { $0.bundleID == id }?.style, .natural, id)
        }
        XCTAssertTrue(FlowAppStyle.codeApps.contains("com.microsoft.VSCode"))
    }

    /// Styles saved on the old "as said" default for those apps move once; any
    /// other style, or another app set to "as said", stays as it was.
    func testOldAsSaidDefaultsMoveToTheCleanUp() {
        let saved = [FlowAppStyle(bundleID: "com.microsoft.VSCode", name: "Visual Studio Code", style: .verbatim),
                     FlowAppStyle(bundleID: "com.apple.mail", name: "Mail", style: .polished),
                     FlowAppStyle(bundleID: "com.example.Editor", name: "Editor", style: .verbatim),
                     FlowAppStyle(bundleID: "com.apple.Terminal", name: "Terminal", style: .polished)]
        XCTAssertEqual(FlowAppStyle.migratingCodeApps(saved).map(\.style), [.natural, .polished, .verbatim, .polished])
    }

    /// The model picked in Flow settings travels with every clean-up; none
    /// picked, Jarvis chooses.
    func testTheCleanUpCarriesThePickedModel() {
        let picked = FlowCleanup.body("uh hi there you", style: .natural, app: "Code", words: ["Supabase"],
                                      model: "claude-haiku-5-5", provider: "anthropic-api")
        XCTAssertEqual(picked["model"] as? String, "claude-haiku-5-5")
        XCTAssertEqual(picked["provider"] as? String, "anthropic-api")
        XCTAssertEqual(picked["style"] as? String, "natural")
        XCTAssertEqual(picked["words"] as? [String], ["Supabase"])
        let auto = FlowCleanup.body("uh hi there you", style: .natural, app: nil, words: [], model: nil, provider: nil)
        XCTAssertNil(auto["model"])
        XCTAssertNil(auto["provider"])
    }

    /// Jarvis's model list (`/api/models`) → the picker's sections, empty
    /// providers left out.
    func testTheModelPickerListsJarvisModels() {
        let json = #"{"groups":[{"provider":"Anthropic API","provider_id":"anthropic-api","models":[{"id":"claude-haiku-5-5","label":"Claude Haiku 5 5"}]},{"provider":"Celeris","provider_id":"celeris","models":[]}]}"#
        let groups = FlowModelCatalog.parse(Data(json.utf8))
        XCTAssertEqual(groups.map(\.provider), ["Anthropic API"])
        XCTAssertEqual(groups.first?.providerID, "anthropic-api")
        XCTAssertEqual(groups.first?.models.map(\.id), ["claude-haiku-5-5"])
        XCTAssertEqual(groups.first?.models.first?.label, "Claude Haiku 5 5")
        XCTAssertTrue(FlowModelCatalog.parse(Data("nope".utf8)).isEmpty)
    }

    func testCleanUpRepliesThatAreNotACleanUpAreRefused() {
        XCTAssertTrue(FlowCleanup.plausible("Meet at four.", from: "uh meet at three no at four"))
        XCTAssertFalse(FlowCleanup.plausible("", from: "one two three"))
        XCTAssertFalse(FlowCleanup.plausible(String(repeating: "word ", count: 40), from: "one two three"))
        XCTAssertFalse(FlowCleanup.plausible("one", from: "one two three four five six seven eight nine ten"))
    }

    func testCleanUpRunsOnlyWhenItCanHelp() {
        XCTAssertTrue(FlowCleanup.worthCleaning("send the report today", style: .natural, enabled: true))
        XCTAssertFalse(FlowCleanup.worthCleaning("send the report today", style: .natural, enabled: false), "off by default")
        XCTAssertFalse(FlowCleanup.worthCleaning("git status now please", style: .verbatim, enabled: true))
        XCTAssertFalse(FlowCleanup.worthCleaning("ok", style: .natural, enabled: true))
    }

    // MARK: history and numbers

    func testHistoryKeepsThirtyDaysByDefault() {
        let now = Date(timeIntervalSince1970: 1_760_000_000)
        let old = FlowEntry(date: now.addingTimeInterval(-31 * 86_400), text: "old", app: nil, words: 1, seconds: 1)
        let fresh = FlowEntry(date: now.addingTimeInterval(-86_400), text: "new", app: nil, words: 1, seconds: 1)
        XCTAssertEqual(FlowHistory.defaultKeepDays, 30)
        XCTAssertEqual(FlowHistory.pruned([fresh, old], keepDays: 30, now: now).map(\.text), ["new"])
        XCTAssertEqual(FlowHistory.pruned([fresh, old], keepDays: -1, now: now).count, 2, "forever")
        XCTAssertEqual(FlowHistory.pruned([fresh, old], keepDays: 0, now: now).count, 0, "not kept")
    }

    func testRecordingADictationCountsItsWords() {
        var stats = FlowStats()
        let day = FlowText.dayKey(Date(timeIntervalSince1970: 1_760_000_000))
        stats.add(words: 12, seconds: 6, app: "Slack", day: day)
        stats.add(words: 3, seconds: 2, app: nil, day: day)
        XCTAssertEqual(stats.days[day]?.words, 15)
        XCTAssertEqual(stats.days[day]?.dictations, 2)
        XCTAssertEqual(stats.apps["Slack"], 12)
    }

    func testSpeedSavedTimeAndStreak() {
        XCTAssertEqual(FlowText.wordsPerMinute(words: 150, seconds: 60), 150)
        XCTAssertEqual(FlowText.wordsPerMinute(words: 10, seconds: 0.5), 0)
        XCTAssertEqual(FlowText.minutesSaved(words: 90, seconds: 30), 1.5, accuracy: 0.001)
        var cal = Calendar(identifier: .gregorian)
        cal.timeZone = TimeZone(identifier: "UTC")!
        let today = Date(timeIntervalSince1970: 1_760_400_000)
        let keys = (1...3).map { FlowText.dayKey(today.addingTimeInterval(Double(-$0) * 86_400), calendar: cal) }
        XCTAssertEqual(FlowText.streak(days: Set(keys), today: today, calendar: cal), 3, "yesterday counts while today is empty")
        XCTAssertEqual(FlowText.streak(days: [], today: today, calendar: cal), 0)
        XCTAssertEqual(FlowText.shortCount(36_800), "36.8K")
        XCTAssertEqual(FlowText.shortCount(950), "950")
    }

    // MARK: transcript merging

    func testARecognizerRestartKeepsTheEarlierWords() {
        var t = DictationTranscript()
        t.absorb("so the plan for friday is")
        t.absorb("ship it")
        XCTAssertEqual(t.text, "so the plan for friday is ship it")
    }

    func testACorrectionReplacesRatherThanAppends() {
        var t = DictationTranscript()
        t.absorb("meet at three")
        t.absorb("meet at three thirty")
        XCTAssertEqual(t.text, "meet at three thirty")
    }

    func testTimedWordsTheRecognizerDroppedArePutBack() {
        typealias P = DictationTranscript.Piece
        var t = DictationTranscript()
        t.absorb("alpha beta gamma", pieces: [P(start: 0, end: 0.3, text: "alpha"), P(start: 0.8, end: 1.1, text: "beta"),
                                              P(start: 1.6, end: 2.0, text: "gamma")])
        t.absorb("alpha gamma delta", pieces: [P(start: 0, end: 0.3, text: "alpha"), P(start: 1.6, end: 2.0, text: "gamma"),
                                               P(start: 2.3, end: 2.7, text: "delta")])
        XCTAssertEqual(t.text, "alpha beta gamma delta")
    }

    // MARK: the pill's dots

    func testBandsCoverTheVoice() {
        let edges = FlowBands.edges()
        XCTAssertEqual(edges.count, FlowBands.count + 1)
        XCTAssertEqual(edges.first!, FlowBands.lowHz, accuracy: 0.001)
        XCTAssertEqual(edges.last!, FlowBands.highHz, accuracy: 0.001)
        let ranges = FlowBands.binRanges(fftSize: 1024, sampleRate: 48_000)
        XCTAssertEqual(ranges.count, FlowBands.count)
        XCTAssertTrue(ranges.allSatisfy { !$0.isEmpty })
        XCTAssertEqual(FlowBands.level(db: -100), 0)
        XCTAssertEqual(FlowBands.level(db: 0), 1)
    }
}
