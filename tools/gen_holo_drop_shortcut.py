#!/usr/bin/env python3
"""Build + sign the "Holo Drop Screen" shortcut: Holo Drop Loading (the island loader, in the
background) → Take Screenshot → Holo Drop Screen (the app's App Intent, screenshot passed in).

Never add Get What's On Screen: on iOS 27.2.1 the Shortcuts runner crashes on it whenever Photos
is in front. Run on a Mac (needs `shortcuts sign`). Writes the signed file
as base64 into ios_app/JarvisCopilot/Copilot/HoloDrop/HoloShortcutFile.swift, so the app can hand
it to Shortcuts in one tap (Holo Drop page → "Add the Back Tap shortcut").

    python3 tools/gen_holo_drop_shortcut.py
"""
from __future__ import annotations

import base64
import plistlib
import subprocess
import sys
import tempfile
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_phone_shortcuts import wrap  # noqa: E402  (same top-level keys as the JC shortcuts)

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "ios_app/JarvisCopilot/Copilot/HoloDrop/HoloShortcutFile.swift"
BUNDLE = "com.jarviscopilot.jarviscopilotMobileAndIOS"
TEAM = "VY5CNF8734"
APP_NAME = "JarvisCopilot"
NAME = "Holo Drop Screen"


def _app_intent(name: str, params: dict | None = None) -> dict:
    return {"WFWorkflowActionIdentifier": f"{BUNDLE}.{name}",
            "WFWorkflowActionParameters": {
                "AppIntentDescriptor": {"AppIntentIdentifier": name, "BundleIdentifier": BUNDLE,
                                        "Name": APP_NAME, "TeamIdentifier": TEAM},
                **(params or {}),
                "UUID": str(uuid.uuid4()).upper()}}


def actions() -> list[dict]:
    shot = str(uuid.uuid4()).upper()
    return [
        # First, so the loader shows while the rest runs (a background Live Activity intent).
        _app_intent("HoloDropLoadingIntent"),
        {"WFWorkflowActionIdentifier": "is.workflow.actions.takescreenshot",
         "WFWorkflowActionParameters": {"UUID": shot}},
        _app_intent("HoloDropScreenIntent", {
            "image": {"Value": {"OutputName": "Screenshot", "OutputUUID": shot, "Type": "ActionOutput"},
                      "WFSerializationType": "WFTextTokenAttachment"}}),
    ]


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        unsigned = Path(tmp) / "unsigned.shortcut"
        signed = Path(tmp) / f"{NAME}.shortcut"
        unsigned.write_bytes(plistlib.dumps(wrap(actions()), fmt=plistlib.FMT_BINARY))
        r = subprocess.run(["shortcuts", "sign", "--mode", "people-who-know-me",
                            "--input", str(unsigned), "--output", str(signed)], capture_output=True, text=True)
        if r.returncode != 0 or not signed.exists():
            print("shortcuts sign failed:", r.stderr or r.stdout, file=sys.stderr)
            return 1
        data = signed.read_bytes()
    b64 = base64.b64encode(data).decode()
    lines = [b64[i:i + 120] for i in range(0, len(b64), 120)]
    OUT.write_text(
        "// Generated by tools/gen_holo_drop_shortcut.py — do not edit by hand.\n"
        "import Foundation\n\n"
        "/// The signed \"Holo Drop Screen\" shortcut (loader → Take Screenshot → Holo Drop Screen), for Back Tap\n"
        "/// and the Control Center button. The Holo Drop page hands it to Shortcuts in one tap.\n"
        "enum HoloShortcutFile {\n"
        f"    static let name = \"{NAME}\"\n"
        "    static var data: Data { Data(base64Encoded: base64.joined()) ?? Data() }\n"
        "    private static let base64: [String] = [\n"
        + "".join(f"        \"{l}\",\n" for l in lines)
        + "    ]\n}\n")
    print(f"signed {len(data)} bytes → {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
