#!/usr/bin/env python3
"""Build + sign the "Holo Drop Screen" shortcut: Get What's On Screen → Take Screenshot → Holo Drop
Screen (the app's App Intent, both passed in). In Photos the first step gives the open photo itself,
so that goes instead of a screenshot; elsewhere it gives nothing (or a page) and the screenshot goes.
Run on a Mac (needs `shortcuts sign`). Writes the signed file as base64 into
ios_app/JarvisCopilot/Copilot/HoloDrop/HoloShortcutFile.swift, so the app can hand it to Shortcuts in
one tap (Holo Drop page → "Add the Holo Drop Screen shortcut").

    python3 tools/gen_holo_drop_shortcut.py
"""
from __future__ import annotations

import base64
import plistlib
import subprocess
import sys
import tempfile
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_phone_shortcuts import wrap  # noqa: E402  (same top-level keys as the JC shortcuts)

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "ios_app/JarvisCopilot/Copilot/HoloDrop/HoloShortcutFile.swift"
BUNDLE = "com.jarviscopilot.jarviscopilotMobileAndIOS"
TEAM = "VY5CNF8734"
APP_NAME = "JarvisCopilot"
NAME = "Holo Drop Screen"


def _output(name: str, uid: str) -> dict:
    return {"Value": {"OutputName": name, "OutputUUID": uid, "Type": "ActionOutput"},
            "WFSerializationType": "WFTextTokenAttachment"}


def actions() -> list[dict]:
    seen = str(uuid.uuid4()).upper()
    shot = str(uuid.uuid4()).upper()
    return [
        # First, while the other app is still in front: Photos hands over the open photo itself.
        {"WFWorkflowActionIdentifier": "is.workflow.actions.getonscreencontent",
         "WFWorkflowActionParameters": {"UUID": seen}},
        {"WFWorkflowActionIdentifier": "is.workflow.actions.takescreenshot",
         "WFWorkflowActionParameters": {"UUID": shot}},
        {"WFWorkflowActionIdentifier": f"{BUNDLE}.HoloDropScreenIntent",
         "WFWorkflowActionParameters": {
             "AppIntentDescriptor": {"AppIntentIdentifier": "HoloDropScreenIntent", "BundleIdentifier": BUNDLE,
                                     "Name": APP_NAME, "TeamIdentifier": TEAM},
             "image": _output("Screenshot", shot),
             "onScreen": _output("What's On Screen", seen),
             "UUID": str(uuid.uuid4()).upper()}},
    ]


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        unsigned = Path(tmp) / "unsigned.shortcut"
        signed = Path(tmp) / f"{NAME}.shortcut"
        unsigned.write_bytes(plistlib.dumps(wrap(actions()), fmt=plistlib.FMT_BINARY))
        r = subprocess.run(["shortcuts", "sign", "--mode", "people-who-know-me",
                            "--input", str(unsigned), "--output", str(signed)], capture_output=True, text=True)
        if r.returncode != 0 or not signed.exists():
            print("shortcuts sign failed:", r.stderr or r.stdout, file=sys.stderr)
            return 1
        data = signed.read_bytes()
    b64 = base64.b64encode(data).decode()
    lines = [b64[i:i + 120] for i in range(0, len(b64), 120)]
    OUT.write_text(
        "// Generated by tools/gen_holo_drop_shortcut.py — do not edit by hand.\n"
        "import Foundation\n\n"
        "/// The signed \"Holo Drop Screen\" shortcut (Get What's On Screen → Take Screenshot → Holo Drop\n"
        "/// Screen), for Back Tap and the Control Center button. The Holo Drop page hands it to\n"
        "/// Shortcuts in one tap.\n"
        "enum HoloShortcutFile {\n"
        f"    static let name = \"{NAME}\"\n"
        "    static var data: Data { Data(base64Encoded: base64.joined()) ?? Data() }\n"
        "    private static let base64: [String] = [\n"
        + "".join(f"        \"{l}\",\n" for l in lines)
        + "    ]\n}\n")
    print(f"signed {len(data)} bytes → {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
